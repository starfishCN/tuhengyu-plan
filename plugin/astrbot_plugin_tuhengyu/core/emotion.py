"""情绪：把一段文本粗分到少量情绪类目 —— 零 token，纯规则。

博士要求「按情绪分类，不需要太细分」：类目固定为下面这几个，
够用、好认、好往目录名上套。

判定就是关键词命中，确定性、零成本。一句里出现多个类目时，取靠前的那个
（顺序即优先级）。都没命中 → None，由上层再按「标签名子串 / default」兜底。
"""
from __future__ import annotations

# 顺序 = 优先级。类目名直接当表情包目录名用（例：stickers/开心/）。
EMOTIONS: list[tuple[str, tuple[str, ...]]] = [
    (
        "开心",
        ("开心", "高兴", "哈哈", "嘿嘿", "嘻嘻", "笑", "棒", "赞", "喜欢",
         "好耶", "愉快", "兴奋", "舒服", "美滋滋", "太好了", "开森"),
    ),
    (
        "难过",
        ("难过", "伤心", "哭", "呜呜", "唉", "委屈", "失落", "遗憾",
         "难受", "心累", "叹气", "惨"),
    ),
    (
        "生气",
        ("生气", "气死", "哼", "讨厌", "烦", "怒", "滚", "别闹",
         "过分", "火大", "恼"),
    ),
    (
        "惊讶",
        ("诶", "咦", "哇", "竟然", "居然", "天哪", "惊", "真的吗", "不是吧"),
    ),
    (
        "害羞",
        ("害羞", "羞", "脸红", "不好意思", "人家"),
    ),
    (
        "无语",
        ("无语", "汗", "呃", "额", "服了", "算了", "罢了", "呵呵", "离谱"),
    ),
]

# 「其他」是不在类目内的目录（default / collected / 自定义名）的归处，不是情绪词。
FALLBACK = "其他"


def labels() -> list[str]:
    """全部情绪类目名，含末尾的「其他」。"""
    return [label for label, _ in EMOTIONS] + [FALLBACK]


def detect(text: str) -> str | None:
    """判断文本属于哪个情绪类目；都不命中返回 None。"""
    if not text:
        return None
    s = str(text)
    for label, words in EMOTIONS:
        if any(w in s for w in words):
            return label
    return None
