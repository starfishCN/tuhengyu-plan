"""意图：把一段文本粗分到少量意图类目 —— 零 token，纯规则。

博士定了方向：分类维度用「意图」而不是「情绪」（看第三方表情包管理器后
由「情绪」改为「意图」）。类目固定为下面这几个。

两条判定路径：
  - 给图片归类：走大模型识图（在 core/classify.py），让它从这几个类目里选。
  - 选图时判 AI 回复：走这里的关键词规则，确定性、零成本。

一句里出现多个类目时，取靠前的那个（顺序即优先级）。
都没命中 → None，由上层再按「标签名子串 / default」兜底。
"""
from __future__ import annotations

# 顺序 = 优先级。类目名直接当表情包目录名用（例：stickers/拒绝/）。
INTENTS: list[tuple[str, tuple[str, ...]]] = [
    (
        "拒绝",
        ("拒绝", "不行", "不要", "免了", "想得美", "没门", "才不", "不干",
         "懒得", "下不为例"),
    ),
    (
        "道歉",
        ("对不起", "抱歉", "不好意思", "是我错", "我的错", "赔罪", "谢罪"),
    ),
    (
        "攻击",
        ("你丫", "闭嘴", "滚", "笨蛋", "傻子", "烦", "哼", "怼",
         "过分", "讨厌", "恼", "别闹", "啰嗦"),
    ),
    (
        "亲昵",
        ("抱", "贴贴", "亲", "摸摸", "好乖", "乖", "蹭", "揉", "撒娇"),
    ),
    (
        "赞同",
        ("好的", "好耶", "没错", "赞成", "可以", "行吧", "嗯嗯", "鼓掌",
         "赞同", "同意", "对哦", "棒", "赞"),
    ),
    (
        "提问",
        ("？", "?", "吗", "呢", "怎么", "为什么", "是不是", "难道",
         "哪里", "什么", "真的吗", "不是吧"),
    ),
    (
        "认输",
        ("认输", "投降", "没辙", "摆烂", "我服", "算了", "算了算了",
         "随便吧", "服了", "罢了", "没办法"),
    ),
    (
        "害羞",
        ("害羞", "羞", "脸红", "人家", "别夸"),
    ),
]

# 「其他」是不在类目内的目录（default / collected / 用户新建分类）的归处。
FALLBACK = "其他"


def labels() -> list[str]:
    """全部意图类目名，含末尾的「其他」。"""
    return [label for label, _ in INTENTS] + [FALLBACK]


def detect(text: str) -> str | None:
    """判断文本属于哪个意图类目；都不命中返回 None。"""
    if not text:
        return None
    s = str(text)
    for label, words in INTENTS:
        if any(w in s for w in words):
            return label
    return None
